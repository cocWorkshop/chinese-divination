export default function XuanjiChat({ readingResult, readingType, readingId }: {
  readingResult: string
  readingType: string
  readingId?: string | null
}) {
  const { data: session } = useSession()
  const { lang } = useLang()
  const [messages, setMessages] = useState<Message[]>([])
  const [input, setInput] = useState('')
  const [loading, setLoading] = useState(false)
  const [initialLoading, setInitialLoading] = useState(false)
  const [chatRemaining, setChatRemaining] = useState<number | null>(null)
  const [usedQuestionIndexes, setUsedQuestionIndexes] = useState<Set<number>>(() => {
    if (typeof window === 'undefined' || !readingId) return new Set()
    try {
      const stored = localStorage.getItem(`xuanji_used_q_${readingId}`)
      return stored ? new Set(JSON.parse(stored)) : new Set()
    } catch { return new Set() }
  })
  const markQuestionUsed = (i: number) => {
    setUsedQuestionIndexes(s => {
      const next = new Set(s).add(i)
      if (readingId) {
        try { localStorage.setItem(`xuanji_used_q_${readingId}`, JSON.stringify(Array.from(next))) } catch {}
      }
      return next
    })
  }
  const [dynamicSuggestions, setDynamicSuggestions] = useState<string[]>([])
  const messagesEndRef = useRef<HTMLDivElement>(null)
  const inputRef = useRef<HTMLInputElement>(null)

  // Load saved chat messages on mount
  useEffect(() => {
    if (!readingId || !session) return
    setInitialLoading(true)
    fetch(`/api/readings/${readingId}/chat`)
      .then(r => r.json())
      .then(data => {
        if (Array.isArray(data.messages) && data.messages.length > 0) {
          setMessages(data.messages.map((m: { role: 'user' | 'assistant'; content: string }) => ({
            role: m.role,
            content: m.content,
          })))
        }
      })
      .catch(() => { /* ignore */ })
      .finally(() => setInitialLoading(false))
  }, [readingId, session])

  // Parse suggestedQuestions from reading result (generated by LLM during divination)
  const dynamicQuestions: { zh: string; en: string }[] | null = (() => {
    if (!readingResult) return null
    try {
      const parsed = JSON.parse(readingResult)
      if (Array.isArray(parsed.suggestedQuestions) && parsed.suggestedQuestions.length >= 3) {
        return parsed.suggestedQuestions.map((q: string) => ({ zh: q, en: q }))
      }
    } catch { /* not valid JSON or no suggestedQuestions */ }
    return null
  })()

  // Scroll to latest message within the chat area (internal scroll only)
  useEffect(() => {
    if (messagesEndRef.current) {
      const container = messagesEndRef.current.parentElement
      if (container) {
        container.scrollTop = container.scrollHeight
      }
    }
  }, [messages])

  const sendMessage = async (text?: string) => {
    const userMsg = (text || input).trim()
    if (!userMsg || loading) return
    setInput('')
    setMessages(prev => [...prev, { role: 'user', content: userMsg }])
    setLoading(true)

    try {
      const controller = new AbortController()
      const timeoutId = setTimeout(() => controller.abort(), 120000)
      const res = await fetch('/api/chat', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          message: userMsg,
          history: messages,
          readingContext: readingResult,
          readingType,
          readingId: readingId || undefined,
          clientTime: new Date().toISOString(),
          lang,
        }),
        signal: controller.signal,
      })
      clearTimeout(timeoutId)
      const data = await res.json()
      if (res.ok) {
        setMessages(prev => [...prev, { role: 'assistant', content: data.reply, suggestions: data.suggestions }])
        if (Array.isArray(data.suggestions) && data.suggestions.length > 0) {
          setDynamicSuggestions(data.suggestions)
        }
        if (data.credits != null) setChatRemaining(data.credits)
        // Save the new user+assistant pair to DB (fire and forget)
        if (readingId) {
          const now = new Date().toISOString()
          fetch(`/api/readings/${readingId}/chat`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
              messages: [
                { role: 'user', content: userMsg, timestamp: now },
                { role: 'assistant', content: data.reply, timestamp: now },
              ],
            }),
          }).catch(() => { /* non-critical */ })
        }
      } else {
        const isCreditsExhausted = res.status === 429 || (data.error && /機緣|額度|karma|credit/i.test(data.error))
        if (isCreditsExhausted) {
          setChatRemaining(0)
          setMessages(prev => [...prev, {
            role: 'assistant',
            content: T(lang, '機緣不足，無法繼續提問', 'Not enough Karma to continue'),
            link: { text: T(lang, '前往機緣商店 →', 'Visit Karma Shop →'), href: '/subscribe' },
          }])
        } else {
          setMessages(prev => [...prev, {
            role: 'assistant',
            content: `${T(lang, '錯誤', 'Error')}：${data.error || T(lang, '請稍後再試', 'Please try again')}`,
            retryMessage: userMsg,
          }])
        }
        reportError({ endpoint: '/api/chat', status: res.status, error: data.error || 'Unknown', context: 'xuanji-chat-tab' })
      }
    } catch (e) {
      const errMsg = e instanceof Error ? e.message : 'Network error'
      setMessages(prev => [...prev, {
        role: 'assistant',
        content: T(lang, '網路連接錯誤', 'Network connection error'),
        retryMessage: userMsg,
      }])
      reportError({ endpoint: '/api/chat', error: errMsg, context: 'xuanji-chat-tab' })
    }
    setLoading(false)
    setTimeout(() => inputRef.current?.focus(), 100)
  }

  const handleRetry = (retryMsg: string, errorIndex: number) => {
    // Remove the error message and the failed user message before it
    setMessages(prev => {
      const newMsgs = [...prev]
      newMsgs.splice(errorIndex, 1) // remove error
      if (errorIndex > 0 && newMsgs[errorIndex - 1]?.role === 'user' && newMsgs[errorIndex - 1]?.content === retryMsg) {
        newMsgs.splice(errorIndex - 1, 1) // remove failed user msg
      }
      return newMsgs
    })
    // Resend
    setTimeout(() => sendMessage(retryMsg), 100)
  }

  const handleKeyDown = (e: React.KeyboardEvent) => {
    if (e.key === 'Enter' && !e.shiftKey) {
      e.preventDefault()
      sendMessage()
    }
  }

  const staticQuestions = suggestedQuestions[readingType] || suggestedQuestions.bazi
  const questions = dynamicQuestions || staticQuestions

  if (!session) {
    return (
      <div className="flex flex-col items-center justify-center py-12 text-center gap-4">
        <YinYangIcon size={48} />
        <p className="text-sm" style={{ color: 'var(--text-muted)' }}>{T(lang, '請登入後使用玄機問答', 'Please sign in to use Q&A')}</p>
        <a href="/login" className="px-4 py-2 rounded-lg text-sm font-semibold hover:opacity-80 transition-colors"
          style={{ backgroundColor: 'var(--gold)', color: 'var(--bg-primary)' }}>
          {T(lang, '登入帳號', 'Sign In')}
        </a>
      </div>
    )
  }

  return (
    <div className="flex flex-col" style={{ minHeight: '400px' }}>
      {/* Messages area */}
      <div className="flex-1 space-y-3 sm:space-y-4 mb-3 sm:mb-4 scrollbar-hide" style={{ maxHeight: '60vh', overflowY: 'auto' }}>
        {initialLoading ? (
          <div className="flex items-center justify-center py-8">
            <MysticalLoader lang={lang} variant="chat" />
          </div>
        ) : messages.length === 0 ? (
          /* Welcome + suggested questions */
          <div className="text-center py-4 sm:py-8">
            <div className="mb-4 sm:mb-6">
              <p className="text-xs" style={{ color: 'var(--text-muted)' }}>
                {T(lang, '針對此次結果，提出您的疑問', 'Ask questions about this reading')}
              </p>
            </div>
            <div className="space-y-2 max-w-sm mx-auto">
              {questions.map((q, i) => (
                  <button
                    key={i}
                    onClick={() => { markQuestionUsed(i); sendMessage(lang === 'en' ? q.en : q.zh) }}
                    className="w-full text-left px-3 py-2.5 sm:px-4 sm:py-3 rounded-xl text-sm transition-all hover:opacity-80"
                    style={{ border: '1px solid var(--border-gold)', color: 'var(--text-secondary)', backgroundColor: 'transparent' }}
                    onMouseEnter={e => { e.currentTarget.style.backgroundColor = 'var(--accent-bg)'; e.currentTarget.style.color = 'var(--gold)' }}
                    onMouseLeave={e => { e.currentTarget.style.backgroundColor = 'transparent'; e.currentTarget.style.color = 'var(--text-secondary)' }}
                  >
                    <span style={{ color: 'var(--gold)', opacity: 0.6 }} className="mr-2">💬</span>
                    {lang === 'en' ? q.en : q.zh}
                  </button>
                ))}
            </div>
          </div>
        ) : (
          /* Chat messages */
          <>
            {messages.map((msg, i) => (
              <div key={i} className={`flex gap-2 sm:gap-3 ${msg.role === 'user' ? 'justify-end' : 'justify-start'}`}>
                {msg.role === 'assistant' && (
                  <div className="w-6 h-6 sm:w-8 sm:h-8 rounded-full flex items-center justify-center flex-shrink-0 mt-1"
                    style={{ backgroundColor: 'rgba(var(--gold-rgb, 212,168,83), 0.15)', border: '1px solid var(--border-gold)' }}>
                    <YinYangIcon size={14} className="sm:hidden" /><YinYangIcon size={18} className="hidden sm:block" />
                  </div>
                )}
                <div
                  className={`rounded-2xl px-3 py-2 sm:px-4 sm:py-3 text-sm leading-relaxed ${msg.role === 'user' ? 'whitespace-pre-wrap' : ''} ${
                    msg.role === 'user' ? 'max-w-[80%] sm:max-w-[70%] rounded-br-sm' : 'max-w-[92%] sm:max-w-[85%] rounded-bl-sm'
                  }`}
                  style={msg.role === 'user'
                    ? { backgroundColor: 'var(--gold)', color: 'var(--bg-primary)' }
                    : { backgroundColor: 'var(--accent-bg)', color: 'var(--text-secondary)', border: '1px solid var(--border-gold)' }
                  }
                >
                  {msg.role === 'assistant' ? (
                    <div className="prose prose-invert prose-sm prose-gold max-w-none [&>p]:my-1 [&>ul]:my-1 [&>ol]:my-1 [&>h1]:text-gold [&>h2]:text-gold [&>h3]:text-gold [&>h4]:text-gold [&>strong]:text-gold/90 [&>ul>li::marker]:text-gold/50 [&>ol>li::marker]:text-gold/50">
                      <ReactMarkdown remarkPlugins={[remarkGfm]}>{msg.content}</ReactMarkdown>
                    </div>
                  ) : (
                    msg.content
                  )}
                  {msg.link && (
                    <a href={msg.link.href} className="block mt-2 text-sm font-semibold underline hover:opacity-80" style={{ color: 'var(--gold)' }}>
                      {msg.link.text}
                    </a>
                  )}
                  {msg.retryMessage && (
                    <button
                      onClick={() => handleRetry(msg.retryMessage!, i)}
                      className="block mt-2 text-sm font-semibold underline hover:opacity-80 cursor-pointer"
                      style={{ color: 'var(--gold)', background: 'none', border: 'none', padding: 0 }}
                    >
                      🔄 {T(lang, '點擊重試', 'Click to retry')}
                    </button>
                  )}
                </div>
              </div>
            ))}
            {loading && (
              <div className="flex gap-2 sm:gap-3 justify-start">
                <div className="w-6 h-6 sm:w-8 sm:h-8 rounded-full flex items-center justify-center flex-shrink-0"
                  style={{ backgroundColor: 'rgba(var(--gold-rgb, 212,168,83), 0.15)', border: '1px solid var(--border-gold)' }}>
                  <YinYangIcon size={14} className="sm:hidden" /><YinYangIcon size={18} className="hidden sm:block" />
                </div>
                <div className="rounded-2xl rounded-bl-sm px-3 py-2 sm:px-4 sm:py-3"
                  style={{ backgroundColor: 'var(--accent-bg)', border: '1px solid var(--border-gold)' }}>
                  <MysticalLoader lang={lang} variant="chat" />
                </div>
              </div>
            )}
            <div ref={messagesEndRef} />
          </>
        )}
      </div>

      {/* Dynamic or static suggested questions */}
      {messages.length > 0 && !loading && (() => {
        // After conversation starts, prefer dynamic suggestions from LLM
        if (dynamicSuggestions.length > 0) {
          return (
            <div className="flex flex-wrap gap-1.5 mb-2">
              {dynamicSuggestions.map((q, i) => (
                <button
                  key={i}
                  onClick={() => { setDynamicSuggestions([]); sendMessage(q) }}
                  className="text-left px-2.5 py-1.5 rounded-lg text-xs transition-all hover:opacity-80"
                  style={{ border: '1px solid var(--border-gold)', color: 'var(--text-secondary)', backgroundColor: 'transparent' }}
                  onMouseEnter={e => { e.currentTarget.style.backgroundColor = 'var(--accent-bg)'; e.currentTarget.style.color = 'var(--gold)' }}
                  onMouseLeave={e => { e.currentTarget.style.backgroundColor = 'transparent'; e.currentTarget.style.color = 'var(--text-secondary)' }}
                >
                  <span style={{ color: 'var(--gold)', opacity: 0.6 }} className="mr-1">💬</span>
                  {q}
                </button>
              ))}
            </div>
          )
        }
        // Fall back to static questions if no dynamic ones yet
        const remaining = questions.map((q, i) => ({ q, i })).filter(({ i }) => !usedQuestionIndexes.has(i))
        if (remaining.length === 0) return null
        return (
          <div className="flex flex-wrap gap-1.5 mb-2">
            {remaining.map(({ q, i }) => (
              <button
                key={i}
                onClick={() => { markQuestionUsed(i); sendMessage(lang === 'en' ? q.en : q.zh) }}
                className="text-left px-2.5 py-1.5 rounded-lg text-xs transition-all hover:opacity-80"
                style={{ border: '1px solid var(--border-gold)', color: 'var(--text-secondary)', backgroundColor: 'transparent' }}
                onMouseEnter={e => { e.currentTarget.style.backgroundColor = 'var(--accent-bg)'; e.currentTarget.style.color = 'var(--gold)' }}
                onMouseLeave={e => { e.currentTarget.style.backgroundColor = 'transparent'; e.currentTarget.style.color = 'var(--text-secondary)' }}
              >
                <span style={{ color: 'var(--gold)', opacity: 0.6 }} className="mr-1">💬</span>
                {lang === 'en' ? q.en : q.zh}
              </button>
            ))}
          </div>
        )
      })()}

      {/* Input area */}
      <div className="pt-2 sm:pt-3 mt-auto" style={{ borderTop: '1px solid var(--border-gold)' }}>
        <div className="flex gap-1.5 sm:gap-2">
          <input
            ref={inputRef}
            type="text"
            value={input}
            onChange={e => setInput(e.target.value)}
            onKeyDown={handleKeyDown}
            placeholder={T(lang, '破解什麼玄機？', 'What mystery to decode?')}
            className="flex-1 rounded-xl px-3 py-2 sm:px-4 sm:py-2.5 text-sm focus:outline-none transition-colors"
            style={{
              backgroundColor: 'var(--input-bg)',
              border: '1px solid var(--border-gold)',
              color: 'var(--text-primary)',
            }}
            disabled={loading || (chatRemaining !== null && chatRemaining <= 0)}
          />
          <button
            onClick={() => sendMessage()}
            disabled={loading || !input.trim() || (chatRemaining !== null && chatRemaining <= 0)}
            className="px-3 py-2 sm:px-4 sm:py-2.5 rounded-xl text-sm font-semibold hover:opacity-80 transition-colors disabled:opacity-30 disabled:cursor-not-allowed whitespace-nowrap"
            style={{ backgroundColor: 'var(--gold)', color: 'var(--bg-primary)' }}
          >
            {chatRemaining !== null
              ? `${T(lang, '發送', 'Send')} (${chatRemaining})`
              : T(lang, '發送', 'Send')
            }
          </button>
        </div>
      </div>
    </div>
  )
}
